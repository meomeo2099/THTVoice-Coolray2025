#!/usr/bin/env python3
"""Bundles worker/src into ONE worker.js for pasting into the Cloudflare dashboard editor.

Each module becomes a closure (no name clashes); imports turn into destructuring.
Usage: python3 worker/scripts/bundle-single-file.py [out=worker/dist/worker.js]
"""
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "src"
ENTRY = "index.js"
IMPORT = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*'\./([\w-]+)\.js';\s*$", re.M)


def var(name):
    return "__m_" + re.sub(r"\W", "_", name)


def parse(name):
    text = (SRC / name).read_text(encoding="utf-8")
    deps = []

    def repl(m):
        dep = m.group(2) + ".js"
        deps.append(dep)
        parts = []
        for item in m.group(1).split(","):
            item = item.strip()
            if not item:
                continue
            if " as " in item:
                a, b = [x.strip() for x in item.split(" as ")]
                parts.append(f"{a}: {b}")
            else:
                parts.append(item)
        return f"const {{ {', '.join(parts)} }} = {var(dep)};"

    text = IMPORT.sub(repl, text)
    exports = []
    text = re.sub(r"^export \{ ([^}]*) \};?\s*$", lambda m: (exports.extend(x.strip() for x in m.group(1).split(",")), "")[1], text, flags=re.M)

    def strip_export(m):
        exports.append(m.group(2))
        return m.group(1)

    text = re.sub(r"^export ((?:async )?function\*? (\w+))", strip_export, text, flags=re.M)
    text = re.sub(r"^export ((?:const|let|class) (\w+))", strip_export, text, flags=re.M)
    has_default = bool(re.search(r"^export default ", text, re.M))
    text = re.sub(r"^export default ", "const __default = ", text, flags=re.M)
    if has_default:
        exports.append("default: __default")
    if re.search(r"^\s*(import|export)\b", text, re.M):
        sys.exit(f"{name}: unsupported import/export form left")
    return text, deps, exports


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC.parent / "dist" / "worker.js"
    order, seen, mods = [], set(), {}

    def visit(name, stack=()):
        if name in seen:
            return
        if name in stack:
            sys.exit(f"import cycle: {' -> '.join(stack + (name,))}")
        mods[name] = parse(name)
        for dep in mods[name][1]:
            visit(dep, stack + (name,))
        seen.add(name)
        order.append(name)

    visit(ENTRY)
    chunks = ["// THT Voice license server — single-file build for the Cloudflare dashboard editor.",
              "// Generated by worker/scripts/bundle-single-file.py from worker/src. Do not edit by hand.", ""]
    for name in order:
        body, _, exports = mods[name]
        chunks.append(f"// ---- {name} " + "-" * max(4, 80 - len(name)))
        chunks.append(f"const {var(name)} = (() => {{\n{body.rstrip()}\nreturn {{ {', '.join(exports)} }};\n}})();\n")
    chunks.append(f"export default {var(ENTRY)}.default;\n")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(chunks), encoding="utf-8")
    print(f"{out} ({out.stat().st_size} bytes, modules: {', '.join(order)})")


main()
